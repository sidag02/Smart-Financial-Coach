# The small dataset's goals and their truth, generated by main's code before stage 9 became a
# sampler (FR-11 milestone 1). Any change to stage 9's output changes this hash
GOALS_HASH = "1f0aaf2a63b285609938b5f23ea4112d7e3c6838357c3e007c15a10acd662de9"


def goals_hash(path: Path) -> str:
    ds = read_sqlite(path)
    parts = []
    for name in ("goals", "truth_goals"):
        t = ds[name].sort_values("goal_id", ignore_index=True)
        parts.append(
            name.encode() + pd.util.hash_pandas_object(t, index=False).to_numpy().tobytes()
        )
    return hashlib.sha256(b"|".join(parts)).hexdigest()


def test_stage_9_still_makes_exactly_todays_goals(small_sqlite: Path) -> None:
    """Against a golden hash from main's code, so a regression in the refactor can't pass by
    agreeing with itself (review on #51)."""
    assert goals_hash(small_sqlite) == GOALS_HASH


def test_the_sampler_reproduces_stage_9_from_the_dataset(small_sqlite: Path) -> None:
    """With each user's own goal stream and the net savings rebuilt from model-visible
    transactions, the sampler gives back the dataset's goals exactly (§6)."""
    ds = read_sqlite(small_sqlite)
    spec = load_spec(PROJECT_ROOT / "configs" / "data" / "small.yaml")
    tl = Timeline(spec.calendar.start, spec.calendar.end)
    start = pd.Period(spec.calendar.start, freq="M")
    seeds = {p.split: p.seed for p in spec.populations}
    txns = ds["transactions"]
    month = (pd.to_datetime(txns["ts"]).dt.to_period("M") - start).map(lambda d: d.n)
    for u in ds["users"].to_dict("records"):
        mine = txns["user_id"] == u["user_id"]
        net = np.bincount(month[mine], weights=txns.loc[mine, "amount"], minlength=tl.n_months)
        persona = spec.personas[u["persona"]]
        goals, truth = sample_goals(
            np.asarray(net, dtype=float),
            tl,
            [g.name for g in persona.goals],
            [g.weight for g in persona.goals],
            spec.goals,
            np.random.default_rng(user_seeds(seeds[u["split"]], u["user_id"])["goals"]),
            user_id=u["user_id"],
            goal_prefix=f"g_{u['user_id'][2:]}",
        )
        stored = ds["goals"][ds["goals"]["user_id"] == u["user_id"]].reset_index(drop=True)
        # Exact values; only dtypes differ (SQLite stores whole-dollar targets as REAL)
        pd.testing.assert_frame_equal(goals, stored, check_dtype=False, check_exact=True)
        stored_truth = ds["truth_goals"][ds["truth_goals"]["goal_id"].isin(stored["goal_id"])]
        pd.testing.assert_frame_equal(
            truth.reset_index(drop=True),
            stored_truth.reset_index(drop=True),
            check_dtype=False,
            check_exact=True,
        )


def test_active_goals_never_count_a_sibling_created_later() -> None:
    """A goal of the set created after this goal's as_of is the future (review on #51)."""
    start = pd.Period("2024-01", freq="M")
    net = np.full(24, 500.0)
    visible = pd.Series(net, index=pd.period_range(start, periods=24, freq="M"))
    goal_set = pd.DataFrame(
        {
            "goal_id": ["a", "b"],
            "created_date": ["2024-02-10", "2025-03-10"],  # b comes later
            "as_of_date": ["2024-08-31", "2025-06-30"],
            "target_date": ["2025-08-31", "2025-11-30"],
            "target_amount": [3000.0, 2000.0],
            "current_balance": [1000.0, 500.0],
            "outcome_class": ["on_track", "on_track"],
            "met": [1, 1],
        }
    )
    user = {"user_id": "u_tr_x_0001", "persona": "young_professional", "split": "train"}
    rows = {r["goal_id"]: r for r in _set_rows(user, goal_set, 0, net, start, visible)}
    assert rows["a"]["active_goals"] == 1  # b didn't exist yet at a's as_of
    assert rows["b"]["active_goals"] == 2  # a is still running at b's as_of


def test_examples_have_both_paths_and_only_known_outcomes(
    examples: Examples, small_sqlite: Path
) -> None:
    f = examples.frame
    assert set(f["path"]) == {"track", "new"}
    assert f.groupby("goal_id")["path"].nunique().eq(2).all()
    assert set(f["met"]) <= {0, 1}
    new = f[f["path"] == "new"]
    assert (new["created_date"] == new["as_of_date"]).all()
    assert (new["origin"] == "yours").all()
    assert set(f["draw"]) == {0, 1, 2}
    known = read_sqlite(small_sqlite)["truth_goals"]["met"].notna().sum()
    assert (f["draw"] == 0).sum() == 2 * known  # the dataset's own goals, on both paths
    assert (f["active_goals"] >= 1).all()


def test_histories_end_at_as_of_and_the_leak_check_proves_it(
    task: GoalForecastingTask, examples: Examples
) -> None:
    splits = task.split(examples, {}, seed=0)
    assert task.leak_errors(examples, splits) == []
    for r in examples.frame.head(50).to_dict("records"):
        history = parse_history(r["history_json"])
        assert history.index[-1] == pd.Period(r["as_of_date"], freq="M")
        future = parse_history(r["future_json"])
        assert future.index[0] == pd.Period(r["as_of_date"], freq="M") + 1
    leaky = examples.frame.head(3).copy()
    leaky["history_json"] = leaky["future_json"]
    assert history_leaks(leaky)


def test_splits_keep_users_whole_and_separate(
    task: GoalForecastingTask, examples: Examples
) -> None:
    splits = task.split(examples, {}, seed=0)
    f = examples.frame.set_index("example_id")
    assert set(f.loc[splits.sets[TRAIN].tolist(), "split"]) == {"train"}
    assert set(f.loc[splits.sets[TEST].tolist(), "split"]) == {"test"}
    for fold in splits.folds:
        held = set(f.loc[next(iter(fold.held_out.values())).tolist(), "user_id"])
        assert held.isdisjoint(f.loc[fold.train.tolist(), "user_id"])


def test_metrics_score_both_paths_and_the_baselines_order(
    task: GoalForecastingTask, examples: Examples
) -> None:
    rows = examples.rows(ids(examples.frame["example_id"]))
    flat = Checked(Flat(0.5), CONTRACT).predict(rows)
    naive = Checked(NaivePace(), CONTRACT).predict(rows)
    m_flat = task.validation_metrics(examples, flat)
    m_naive = task.validation_metrics(examples, naive)
    assert m_flat["brier.track"] == pytest.approx(0.25)
    assert m_flat["brier.new"] == pytest.approx(0.25)
    assert m_flat["neg_brier"] == pytest.approx(-0.25)
    assert m_naive["brier.track"] > 0.25  # the naive call is worse than a coin on this data
    assert np.isnan(m_flat["coverage.track"])  # no share, no coverage
    lo, hi = task.selection_interval(examples, flat)
    assert lo == pytest.approx(-0.25)
    assert hi == pytest.approx(-0.25)
    assert not task.tied(examples, flat, naive)


def passing_metrics() -> dict[str, float]:
    m: dict[str, float] = {"test_brier.track": 0.17, "test_brier.new": 0.21}
    for path in ("track", "new"):
        m[f"test_coverage.{path}"] = 0.82
        for persona in ("family_budgeter", "freelancer", "young_professional"):
            m[f"test_brier.{path}.{persona}"] = 0.2
        for scope in ("", ".family_budgeter", ".freelancer", ".young_professional"):
            for band, rate in (("off", 0.2), ("either", 0.5), ("on", 0.8)):
                m[f"test_met_rate.{path}{scope}.{band}"] = rate
    return m


def test_gates_follow_the_design_and_decision_6(task: GoalForecastingTask) -> None:
    base = {"test_brier.track": 0.3, "test_brier.new": 0.3}
    metrics = passing_metrics() | {"test_brier.new.freelancer": 0.26}  # over a flat 50%
    gates = {g.name: g for g in task.gates(metrics, {"naive_pace": base, "flat_50": base})}
    freelancer = gates["brier_new_freelancer_below_flat"]
    assert (freelancer.passed, freelancer.blocking) == (False, False)  # reported, not blocking
    assert all(g.passed for g in gates.values() if g.blocking)
    assert gates["brier_track_freelancer_below_flat"].blocking
    # Naive pace is a floor with a track record only (review on #51)
    assert "brier_track_below_naive_pace" in gates
    assert "brier_new_below_naive_pace" not in gates
    # Calibration is gated per persona too (decision 6)
    assert "calibrated_new_family_budgeter_on" in gates


def test_tolerances_come_from_validation(task: GoalForecastingTask) -> None:
    """One reading of "within tolerance": the target widens by half the validation interval of
    the same metric, logged before test (review on #51)."""
    base = {"test_brier.track": 0.3, "test_brier.new": 0.3}
    baselines = {"naive_pace": base, "flat_50": base}
    over = passing_metrics() | {
        "test_brier.track.family_budgeter": 0.27,
        "test_met_rate.track.on": 0.66,
    }
    strict = {g.name: g for g in task.gates(over, baselines)}
    assert not strict["brier_track_family_budgeter_below_flat"].passed
    assert not strict["calibrated_track_on"].passed
    tolerant = over | {
        "val_brier.track.family_budgeter_lo": 0.18,
        "val_brier.track.family_budgeter_hi": 0.24,  # half-width 0.03: up to 0.28
        "val_met_rate.track.on_lo": 0.70,
        "val_met_rate.track.on_hi": 0.80,  # half-width 0.05: from 0.65
    }
    loose = {g.name: g for g in task.gates(tolerant, baselines)}
    assert loose["brier_track_family_budgeter_below_flat"].passed
    assert loose["calibrated_track_on"].passed


